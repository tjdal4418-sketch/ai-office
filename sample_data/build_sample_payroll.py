def make(path: Path, client: str, employees: list, payees: list, with_prev: bool = True) -> None:
    wb = Workbook()
    info = wb.active
    info.title = "정보"
    info.append(["귀속월", "2026-10"])
    info.append(["고객사", client])
    info.append(["비고", "가상 샘플 데이터 — 실제 회사·인물과 무관"])
    ws = wb.create_sheet("급여대장")
    ws.append(HEAD)
    for e in employees:
        ws.append(list(e[:10]))
    ws2 = wb.create_sheet("소득자지급내역")
    ws2.append(PAYEE_HEAD)
    for p in payees:
        ws2.append(list(p))
    if with_prev:
        ws3 = wb.create_sheet("전월급여")
        ws3.append(["사번", "총지급액"])
        for e in employees:
            if e[10] is not None:
                ws3.append([e[0], e[10]])
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)


