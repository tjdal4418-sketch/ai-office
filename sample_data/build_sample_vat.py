def write(path: Path, header: list, rows: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def invoice_rows(own_biz: str, own_name: str, rows: list, sales: bool) -> list:
    out = []
    for n, (wd, idate, biz, name, supply, item) in enumerate(rows, 1):
        tax = int(supply * 0.1)
        appr = f"{wd.replace('-', '')}{'1' if sales else '2'}{n:07d}"
        sup_biz, sup_name, buy_biz, buy_name = (own_biz, own_name, biz, name) if sales else (biz, name, own_biz, own_name)
        out.append([wd, idate, appr, sup_biz, sup_name, buy_biz, buy_name, supply + tax, supply, tax, item, ""])
    return out


def build(client_id: str, sales, purchase, ledger, card) -> None:
    own_biz, own_name = OWN[client_id]
    folder = OUT / client_id
    write(folder / "sales_invoices.csv", INV_HEAD, invoice_rows(own_biz, own_name, sales, True))
    write(folder / "purchase_invoices.csv", INV_HEAD, invoice_rows(own_biz, own_name, purchase, False))
    write(folder / "ledger.csv", LEDGER_HEAD, ledger)
    write(folder / "card_purchases.csv", CARD_HEAD, [[d, n, b, s, t, s + t, m] for d, n, b, s, t, m in card])


