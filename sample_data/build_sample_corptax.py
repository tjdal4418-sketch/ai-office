def rows_with_plug(accounts: list) -> list:
    """이익잉여금을 차대 균형에 맞게 추가. 반환: CSV 행 목록."""
    rows, dr, cr = [], 0, 0
    for code, name, kind, normal, amt in accounts:
        d, c = (amt, 0) if normal == "차변" else (0, amt)
        dr, cr = dr + d, cr + c
        rows.append([code, name, kind, normal, d or "", c or ""])
    diff = dr - cr
    rows.append(["375", "이익잉여금", "자본", "대변", -diff if diff < 0 else "", diff if diff > 0 else ""])
    return rows


def write(path: Path, rows: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEAD)
        w.writerows(rows)


