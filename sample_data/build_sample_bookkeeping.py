def write(path: Path, header: list, rows: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def bank_rows_with_balance(opening: int, rows: list, gap_after: int | None = None, gap: int = 0) -> list:
    """잔액 열을 계산해 붙인다. gap_after 번째 거래 뒤부터 은행 내역에 없는 변동(gap)이 섞인 것처럼 만든다."""
    bal, out = opening, []
    for i, (d, memo, party, inflow, outflow) in enumerate(rows, 1):
        bal += inflow - outflow
        if gap_after is not None and i == gap_after + 1:
            bal += gap  # 은행이 내역에 안 보이는 수수료·자동이체를 빼간 상황
        out.append([d, memo, party, inflow or "", outflow or "", bal])
    return out


def build_client(client_id: str, opening: list, bank: list, bank_open: int, lag: list, card: list,
                 gap_after=None, gap=0) -> None:
    folder = OUT / client_id
    write(folder / "accounts.csv", ["계정코드", "계정과목", "구분", "정상잔액"], CHART)
    write(folder / "opening.csv", ["계정코드", "차변", "대변", "발생일"],
          [[c, dr or "", cr or "", d] for c, dr, cr, d in opening])
    write(folder / "bank.csv", ["거래일자", "적요", "거래처", "입금", "출금", "잔액"],
          bank_rows_with_balance(bank_open, bank, gap_after, gap))
    write(folder / "lag_items.csv", ["구분", "일자", "적요", "거래처", "입금", "출금"],
          [[k, d, m, p, i or "", o or ""] for k, d, m, p, i, o in lag])
    write(folder / "card.csv", ["사용일자", "가맹점", "적요", "금액", "결제예정일"], card)


